<script setup lang="ts">
import { computed } from 'vue';
import { QuireIcon } from '@quirekit/ui/vue';
import { QuireMarkdown } from '@quirekit/incremark/vue';
import { articles } from '../content';
const props = defineProps<{ slug: string }>();
const article = computed(() => articles.find(post => post.slug === props.slug));
const nextArticle = computed(() => articles.find(post => post.slug !== props.slug)!);
const headings = computed(() => article.value?.content.split('\n').filter(line => line.startsWith('## ')).map(line => line.slice(3)) ?? []);

/** Scrolls to the actual semantic heading generated by QuireMarkdown.
 * @param title - Exact visible section title.
 */
function jumpTo(title: string): void {
  const heading = [...document.querySelectorAll('.reading-body h2')].find(node => node.textContent === title);
  heading?.scrollIntoView({ behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'instant' : 'smooth', block: 'start' });
}
</script>

<template>
  <article v-if="article" class="reading-page">
    <a href="#/articles" class="back-link"><QuireIcon name="arrowLeft" :size="16" /> 所有文章</a>
    <header class="reading-header"><div class="reading-meta"><span>{{ article.category }}</span><span>·</span><time>{{ article.date }}</time></div><h1 class="qk-type-display">{{ article.title }}</h1><p>{{ article.summary }}</p><div class="author-line"><span class="author-avatar">Y</span><span>Yishuai</span><span class="reading-time">{{ Math.max(2, Math.ceil(article.content.length / 350)) }} 分钟阅读</span></div></header>
    <div class="reading-layout"><div class="reading-body"><QuireMarkdown :content="article.content" :identity="article.slug" /><div class="article-colophon"><span>写于 {{ article.date }}</span><span>谢谢你读到这里。</span></div><a class="next-article" :href="`#/articles/${nextArticle.slug}`"><span class="eyebrow">接着读</span><strong class="qk-type-section-title">{{ nextArticle.title }}</strong><QuireIcon name="arrowRight" :size="16" /></a></div><aside class="reading-outline" aria-label="文章目录"><span class="eyebrow">本篇目录</span><button v-for="heading in headings" :key="heading" @click="jumpTo(heading)">{{ heading }}</button><span class="outline-note">留一点时间，<br />读一点文字。</span></aside></div>
  </article>
  <div v-else class="page-intro"><h1 class="qk-type-page-title">这篇文章还没写到这里。</h1><a href="#/articles" class="text-link">回到所有文章</a></div>
</template>
