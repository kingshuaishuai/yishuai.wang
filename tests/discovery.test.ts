import { afterAll, beforeAll, expect, it, vi } from 'vitest';
import { createServer, type Server } from 'node:http';
import { createApp, createRouter, defineEventHandler, toNodeListener } from 'h3';
import type { PlatformProxy } from 'wrangler';
import type { Bindings } from '../server/domain/types';
import { testDatabase } from './support/database';
import { createPost, savePost, transitionPost } from '../server/domain/posts';
import { normalizeContent } from '../server/domain/content';
import { createTranslation } from '../server/domain/translations';
import { discoveryEntries } from '../server/domain/discovery/read';
import { sitemap, llms } from '../server/domain/resources';
import sitemapHandler from '../server/routes/sitemap.xml.get';
import sitemapHeadHandler from '../server/routes/sitemap.xml.head';

let platform: PlatformProxy<Bindings>, server: Server, origin: string;
beforeAll(async () => {
  platform = await testDatabase();
  vi.stubGlobal('useRuntimeConfig', () => ({ public: { siteUrl: origin } }));
  const app = createApp();
  app.use(defineEventHandler(event => { event.context.cloudflare = { env: platform.env }; }));
  app.use(createRouter().get('/sitemap.xml', sitemapHandler).head('/sitemap.xml', sitemapHeadHandler));
  server = createServer(toNodeListener(app));
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  origin = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
}, 60000);
afterAll(async () => { server?.closeAllConnections(); await new Promise<void>(resolve => server?.close(() => resolve())); await platform?.dispose(); vi.unstubAllGlobals(); });

it('uses public metadata only, preserves lastmod for draft edits and removes withdrawn language versions', async () => {
  const db = platform.env.BLOG_DB;
  let zh = await createPost(db, 'owner', normalizeContent({ kind: 'article', title: '中文 & <索引>', summary: 'Public Chinese summary', markdown: 'Not an index payload' }), 'discovery');
  expect(await discoveryEntries(db)).toHaveLength(0);
  zh = await transitionPost(db, zh.id, zh.version, 'publish');
  const lastmod = (await discoveryEntries(db))[0]!.updatedAt;
  zh = await savePost(db, zh.id, zh.version, { ...zh, title: 'PRIVATE', markdown: 'private body' });
  let en = await createTranslation(db, zh.id, 'en');
  en = await savePost(db, en.id, en.version, { ...en, title: 'English', summary: 'Public English summary', markdown: 'English body' });
  expect((await discoveryEntries(db))[0]).toMatchObject({ title: '中文 & <索引>', updatedAt: lastmod, translations: [{ language: 'zh', url: '/articles/discovery' }] });
  en = await transitionPost(db, en.id, en.version, 'publish');
  const entries = await discoveryEntries(db), xml = sitemap(entries, origin);
  expect(JSON.stringify(entries)).not.toMatch(/PRIVATE|private body|English body|Not an index payload/);
  expect(entries[0]!.translations).toEqual(entries[1]!.translations);
  expect(xml).toContain('xmlns:xhtml="http://www.w3.org/1999/xhtml"');
  expect(xml.match(/<url>/g)).toHaveLength(14);
  expect(xml).toContain(`hreflang="en" href="${origin}/en/articles/${en.slug}"`);
  expect(xml).not.toMatch(/<loc>[^<]*\/(manage|write|analytics|api)\b/);
  expect(llms(entries, origin)).toContain('/articles/discovery.md');
  const initial = await fetch(origin + '/sitemap.xml'), etag = initial.headers.get('etag')!;
  expect(initial.status).toBe(200); expect(initial.headers.get('content-type')).toContain('application/xml');
  expect(initial.headers.get('cache-control')).toContain('must-revalidate');
  expect(await initial.text()).toBe(xml);
  const head = await fetch(origin + '/sitemap.xml', { method: 'HEAD' });
  expect(head.status).toBe(200); expect(head.headers.get('etag')).toBe(etag);
  expect(head.headers.get('content-type')).toContain('application/xml');
  expect(await head.text()).toBe('');
  const unchanged = await fetch(origin + '/sitemap.xml', { headers: { 'if-none-match': `W/${etag}` } });
  expect(unchanged.status).toBe(304); expect(await unchanged.text()).toBe('');
  en = await transitionPost(db, en.id, en.version, 'unpublish');
  const withdrawn = await fetch(origin + '/sitemap.xml', { headers: { 'if-none-match': etag } });
  expect(withdrawn.status).toBe(200); expect(withdrawn.headers.get('etag')).not.toBe(etag);
  expect(await withdrawn.text()).not.toContain(`/en/articles/${en.slug}`);
  await transitionPost(db, zh.id, zh.version, 'delete');
  expect(await discoveryEntries(db)).toHaveLength(0);
});
